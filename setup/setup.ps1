# One-click setup for the LiteLLM + MCP gateway + Kilo Code stack, Windows.
# Run from anywhere - it locates the project root relative to this script.
# Usage:  powershell -ExecutionPolicy Bypass -File setup\setup.ps1

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot

function Write-Step($msg) { Write-Host "`n=== $msg ===" -ForegroundColor Cyan }
function New-RandomSecret([int]$len = 32) {
    -join ((48..57) + (65..90) + (97..122) | Get-Random -Count $len | ForEach-Object { [char]$_ })
}
function Read-OptionalKey($label) {
    Read-Host "$label (leave blank to fill in later)"
}

# ---------- 1. Docker ----------
Write-Step "Checking Docker"
$dockerOk = $false
try { docker info *> $null; if ($LASTEXITCODE -eq 0) { $dockerOk = $true } } catch {}

if (-not $dockerOk) {
    Write-Host "Docker doesn't appear to be installed/running."
    $install = Read-Host "Install Docker Desktop now via winget? (y/n)"
    if ($install -eq "y") {
        winget install -e --id Docker.DockerDesktop
        Write-Host "`nDocker Desktop installed. Start it, then re-run this script." -ForegroundColor Yellow
    } else {
        Write-Host "Install Docker Desktop manually (https://docker.com/products/docker-desktop), then re-run this script." -ForegroundColor Yellow
    }
    exit 1
}
Write-Host "Docker is up."

# ---------- 2. .env ----------
Write-Step "Configuring .env"
$envPath = Join-Path $root ".env"
$writeEnv = $true
if (Test-Path $envPath) {
    $overwrite = Read-Host "$envPath already exists. Overwrite? (y/N)"
    $writeEnv = ($overwrite -eq "y")
}

if ($writeEnv) {
    $postgresPassword = New-RandomSecret
    $masterKey = New-RandomSecret

    Write-Host "`nProvider API keys - leave any blank to configure later by editing .env directly.`n"
    $openrouter = Read-OptionalKey "OpenRouter API key"
    $deepinfra = Read-OptionalKey "DeepInfra API key"
    $fireworks = Read-OptionalKey "Fireworks AI API key"
    $anthropic = Read-OptionalKey "Anthropic API key (for the 'claude' escape-hatch model - needs its own paid credits, separate from a Claude subscription)"
    $gemini = Read-OptionalKey "Google Gemini API key (for the 'gemini' escape-hatch model - needs an AI Studio key, separate from a Gemini subscription)"

    Write-Host "`nOptional: MCP servers that need their own credentials (all blank/skippable):`n"
    $sshHost = Read-OptionalKey "SSH target host (for the ssh MCP server)"
    $sshUser = Read-OptionalKey "SSH username"
    $sshPass = Read-OptionalKey "SSH password"
    $meshy = Read-OptionalKey "Meshy AI API key (3D generation)"
    $tripo = Read-OptionalKey "Tripo3D API secret (3D generation)"
    $elevenlabs = Read-OptionalKey "ElevenLabs API key (voice/audio generation)"
    $acedata = Read-OptionalKey "AceDataCloud API token (Suno music generation)"

    @"
# Generated by setup.ps1 on $(Get-Date -Format o) - not committed to git.

# --- Postgres ---
POSTGRES_USER=llmproxy
POSTGRES_PASSWORD=$postgresPassword
POSTGRES_DB=litellm
DATABASE_URL=postgresql://llmproxy:$postgresPassword@postgres:5432/litellm

# --- LiteLLM ---
LITELLM_MASTER_KEY=$masterKey

# --- Model providers ---
OPENROUTER_API_KEY=$openrouter
DEEPINFRA_API_KEY=$deepinfra
FIREWORKS_AI_API_KEY=$fireworks
ANTHROPIC_API_KEY=$anthropic
GEMINI_API_KEY=$gemini

# --- MCP filesystem server scope (default: safe, this project only, read-only) ---
MCP_FILESYSTEM_HOST_PATH=.
MCP_FILESYSTEM_MODE=ro

# --- MCP servers needing their own credentials ---
SSH_HOST=$sshHost
SSH_PORT=22
SSH_USERNAME=$sshUser
SSH_PASSWORD=$sshPass
MESHY_API_KEY=$meshy
TRIPO_API_SECRET=$tripo
ELEVENLABS_API_KEY=$elevenlabs
ACEDATACLOUD_API_TOKEN=$acedata
"@ | Set-Content -Path $envPath -Encoding utf8

    Write-Host "Wrote $envPath (Postgres password and LiteLLM master key were freshly generated)."
} else {
    Write-Host "Keeping existing .env - reading master key from it for the summary below."
    $masterKey = (Get-Content $envPath | Where-Object { $_ -match '^LITELLM_MASTER_KEY=' }) -replace '^LITELLM_MASTER_KEY=', ''
}

# ---------- 3. Build + start ----------
Write-Step "Building the LiteLLM image (adds Node/Python/Go/ffmpeg for MCP servers - first run takes a few minutes)"
docker compose -f (Join-Path $root "docker-compose.yaml") --project-directory $root build litellm

Write-Step "Starting Postgres + LiteLLM"
docker compose -f (Join-Path $root "docker-compose.yaml") --project-directory $root up -d

Write-Step "Waiting for LiteLLM to become healthy"
$healthy = $false
for ($i = 0; $i -lt 40; $i++) {
    try {
        $resp = Invoke-WebRequest -Uri "http://localhost:4000/health/liveliness" -UseBasicParsing -TimeoutSec 3
        if ($resp.StatusCode -eq 200) { $healthy = $true; break }
    } catch {}
    Start-Sleep -Seconds 3
}
if ($healthy) { Write-Host "LiteLLM is up at http://localhost:4000" } else { Write-Host "Still not healthy after ~2 min - check 'docker compose logs litellm'." -ForegroundColor Yellow }

# ---------- 4. VS Code extension ----------
Write-Step "Installing the provider-balance VS Code extension"
$vsix = Join-Path $root "vscode-extension\litellm-provider-balance\litellm-provider-balance-0.0.2.vsix"
if (Get-Command code -ErrorAction SilentlyContinue) {
    if (Test-Path $vsix) {
        code --install-extension $vsix
    } else {
        Write-Host "Couldn't find $vsix - skipping." -ForegroundColor Yellow
    }
} else {
    Write-Host "VS Code CLI ('code') isn't on PATH - install the extension manually later: code --install-extension `"$vsix`"" -ForegroundColor Yellow
}

# ---------- 4b. Kilo Code shell-permission fix ----------
Write-Step "Kilo Code shell-permission fix"
# Kilo Code reads a project-root kilo.json separate from kilo.jsonc. If it's
# ever empty/invalid JSON, Kilo Code silently denies all shell/bash commands
# even with everything else (workspace trust, Auto-Approve) set correctly.
$kiloJsonPath = Join-Path $root "kilo.json"
$needsFix = $true
if (Test-Path $kiloJsonPath) {
    $content = Get-Content $kiloJsonPath -Raw -ErrorAction SilentlyContinue
    if ($content -and $content.Trim().Length -gt 0) {
        try { $null = $content | ConvertFrom-Json; $needsFix = $false } catch { $needsFix = $true }
    }
}
if ($needsFix) {
    @'
{
  "$schema": "https://app.kilo.ai/config.json",
  "permission": {
    "bash": "allow"
  }
}
'@ | Set-Content -Path $kiloJsonPath -Encoding utf8
    Write-Host "Wrote/repaired $kiloJsonPath."
} else {
    Write-Host "$kiloJsonPath already valid - left as-is."
}

# ---------- 4c. Model auto-refresh ----------
Write-Step "Model auto-refresh (optional)"
Write-Host "scripts/refresh_models.py periodically checks for cheaper/newer models at your"
Write-Host "configured providers and safely upgrades config.yaml (live-tested, old model kept"
Write-Host "as a fallback, every change is its own git commit). See that file's docstring."
$pythonExe = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $pythonExe) { $pythonExe = (Get-Command python3 -ErrorAction SilentlyContinue).Source }
if ($pythonExe) {
    & $pythonExe -m pip install --quiet -r (Join-Path $root "scripts\requirements.txt")
    $setupSchedule = Read-Host "Set up a weekly scheduled run now? (y/N)"
    if ($setupSchedule -eq "y") {
        & powershell -ExecutionPolicy Bypass -File (Join-Path $root "scripts\schedule_refresh.ps1")
    } else {
        Write-Host "Skipped. Run it any time yourself: python `"$(Join-Path $root 'scripts\refresh_models.py')`" --dry-run"
    }
} else {
    Write-Host "Python not found on PATH - skipping. Install Python 3, then optionally run scripts\schedule_refresh.ps1 later." -ForegroundColor Yellow
}

# ---------- 5. Manual steps ----------
Write-Step "Manual step required: Kilo Code provider wiring"
Write-Host @"
Kilo Code's own provider config isn't reliably settable by dropping a file
in - do this once through its UI:
  1. Install the Kilo Code extension in VS Code if you haven't.
  2. Settings -> Providers -> Custom provider -> Connect
       Base URL : http://localhost:4000/v1
       API key  : $masterKey
  3. Settings -> Models -> "Model per Mode" -> set Code/Ask/Debug/Plan/
     Orchestrator to their matching kilo-* model from the new provider.
"@

Write-Step "Optional: host-side companion MCP servers"
Write-Host @"
These need their real app running on THIS machine (not in Docker) - set up
only the ones you actually use:

  Blender  - install github.com/ahujasid/blender-mcp's addon, open Blender,
             click "Start MCP Server" in its sidebar (port 9876 - the
             container already reaches it via host.docker.internal).

  Godot    - open your project (the gdai-mcp-plugin-godot addon is already
             in Nebula Knockout), then run:
               pip install mcp httpx jsonschema
               python addons\gdai-mcp-plugin-godot\gdai_mcp_server.py --transport http --host 0.0.0.0 --port 9090
             Then add a remote entry in config.yaml pointing at
             http://host.docker.internal:9090/mcp and rebuild.

  Unity    - open your Unity project, install the Unity MCP package, then
             run Window -> MCP for Unity -> Configure All Detected Clients
             to see its real connection details (not fixed in advance).

  Nuclear  - install from nuclearplayer.com, enable Settings -> Integrations
             -> MCP Server, then register the URL it gives you.

  Windows desktop control (CursorTouch/Windows-MCP) - powerful: any client
             connected to the gateway gets it too. Only if you want that:
               pip install uv
               uvx windows-mcp --transport http --port 8091
             Register http://host.docker.internal:8091/mcp as a remote
             MCP server, ideally as a scheduled task so it's always running.
"@

Write-Step "Done"
Write-Host "LiteLLM:      http://localhost:4000"
Write-Host "Admin UI:     http://localhost:4000 (log in with the master key above)"
Write-Host "Master key:   $masterKey"
