#!/usr/bin/env bash
# One-click setup for the LiteLLM + MCP gateway + Kilo Code stack, Linux/macOS.
# Usage: chmod +x setup/setup.sh && ./setup/setup.sh

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

step() { printf "\n=== %s ===\n" "$1"; }
random_secret() { openssl rand -hex 16 2>/dev/null || head -c 32 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 32; }
read_optional() { local prompt="$1"; read -r -p "$prompt (leave blank to fill in later): " val; echo "$val"; }

# ---------- 1. Docker ----------
step "Checking Docker"
if ! docker info >/dev/null 2>&1; then
  echo "Docker doesn't appear to be installed/running."
  if command -v apt-get >/dev/null 2>&1; then
    read -r -p "Install Docker now via get.docker.com's official script? (y/n): " install
    if [ "$install" = "y" ]; then
      curl -fsSL https://get.docker.com | sh
      echo "Docker installed. You may need to log out/in for group membership to take effect, then re-run this script."
    else
      echo "Install Docker manually (https://docs.docker.com/engine/install/), then re-run this script."
    fi
  else
    echo "Install Docker manually for your distro (https://docs.docker.com/engine/install/), then re-run this script."
  fi
  exit 1
fi
echo "Docker is up."

# ---------- 2. .env ----------
step "Configuring .env"
ENV_PATH="$ROOT/.env"
WRITE_ENV=true
if [ -f "$ENV_PATH" ]; then
  read -r -p "$ENV_PATH already exists. Overwrite? (y/N): " overwrite
  [ "$overwrite" = "y" ] || WRITE_ENV=false
fi

if [ "$WRITE_ENV" = true ]; then
  POSTGRES_PASSWORD=$(random_secret)
  MASTER_KEY=$(random_secret)

  echo
  echo "Provider API keys — leave any blank to configure later by editing .env directly."
  echo
  OPENROUTER=$(read_optional "OpenRouter API key")
  DEEPINFRA=$(read_optional "DeepInfra API key")
  FIREWORKS=$(read_optional "Fireworks AI API key")
  ANTHROPIC=$(read_optional "Anthropic API key (for the 'claude' escape-hatch model — needs its own paid credits, separate from a Claude subscription)")
  GEMINI=$(read_optional "Google Gemini API key (for the 'gemini' escape-hatch model — needs an AI Studio key, separate from a Gemini subscription)")

  echo
  echo "Optional: MCP servers that need their own credentials (all blank/skippable):"
  echo
  SSH_HOST_V=$(read_optional "SSH target host (for the ssh MCP server)")
  SSH_USER_V=$(read_optional "SSH username")
  SSH_PASS_V=$(read_optional "SSH password")
  MESHY=$(read_optional "Meshy AI API key (3D generation)")
  TRIPO=$(read_optional "Tripo3D API secret (3D generation)")
  ELEVENLABS=$(read_optional "ElevenLabs API key (voice/audio generation)")
  ACEDATA=$(read_optional "AceDataCloud API token (Suno music generation)")

  cat > "$ENV_PATH" <<EOF
# Generated by setup.sh on $(date -Iseconds) — not committed to git.

# --- Postgres ---
POSTGRES_USER=llmproxy
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_DB=litellm
DATABASE_URL=postgresql://llmproxy:$POSTGRES_PASSWORD@postgres:5432/litellm

# --- LiteLLM ---
LITELLM_MASTER_KEY=$MASTER_KEY

# --- Model providers ---
OPENROUTER_API_KEY=$OPENROUTER
DEEPINFRA_API_KEY=$DEEPINFRA
FIREWORKS_AI_API_KEY=$FIREWORKS
ANTHROPIC_API_KEY=$ANTHROPIC
GEMINI_API_KEY=$GEMINI

# --- MCP filesystem server scope (default: safe, this project only, read-only) ---
MCP_FILESYSTEM_HOST_PATH=.
MCP_FILESYSTEM_MODE=ro

# --- MCP servers needing their own credentials ---
SSH_HOST=$SSH_HOST_V
SSH_PORT=22
SSH_USERNAME=$SSH_USER_V
SSH_PASSWORD=$SSH_PASS_V
MESHY_API_KEY=$MESHY
TRIPO_API_SECRET=$TRIPO
ELEVENLABS_API_KEY=$ELEVENLABS
ACEDATACLOUD_API_TOKEN=$ACEDATA
EOF
  echo "Wrote $ENV_PATH (Postgres password and LiteLLM master key were freshly generated)."
else
  echo "Keeping existing .env — reading master key from it for the summary below."
  MASTER_KEY=$(grep '^LITELLM_MASTER_KEY=' "$ENV_PATH" | cut -d= -f2-)
fi

# ---------- 3. Build + start ----------
step "Building the LiteLLM image (adds Node/Python/Go/ffmpeg for MCP servers — first run takes a few minutes)"
docker compose -f "$ROOT/docker-compose.yaml" --project-directory "$ROOT" build litellm

step "Starting Postgres + LiteLLM"
docker compose -f "$ROOT/docker-compose.yaml" --project-directory "$ROOT" up -d

step "Waiting for LiteLLM to become healthy"
healthy=false
for i in $(seq 1 40); do
  if curl -s -o /dev/null -w "%{http_code}" http://127.0.0.1:4000/health/liveliness | grep -q 200; then
    healthy=true
    break
  fi
  sleep 3
done
if [ "$healthy" = true ]; then
  echo "LiteLLM is up at http://127.0.0.1:4000"
else
  echo "Still not healthy after ~2 min — check 'docker compose logs litellm'."
fi

# ---------- 4. VS Code extension ----------
step "Installing the provider-balance VS Code extension"
VSIX="$ROOT/vscode-extension/litellm-provider-balance/litellm-provider-balance-0.0.2.vsix"
if command -v code >/dev/null 2>&1; then
  if [ -f "$VSIX" ]; then
    code --install-extension "$VSIX"
  else
    echo "Couldn't find $VSIX — skipping."
  fi
else
  echo "VS Code CLI ('code') isn't on PATH — install the extension manually later: code --install-extension \"$VSIX\""
fi

# ---------- 4b. Kilo Code shell-permission fix ----------
step "Kilo Code shell-permission fix"
# Kilo Code reads a project-root kilo.json separate from kilo.jsonc. If it's
# ever empty/invalid JSON, Kilo Code silently denies all shell/bash commands
# even with everything else (workspace trust, Auto-Approve) set correctly.
KILO_JSON="$ROOT/kilo.json"
NEEDS_FIX=true
if [ -s "$KILO_JSON" ]; then
  if command -v python3 >/dev/null 2>&1 && python3 -c "import json,sys; json.load(open(sys.argv[1]))" "$KILO_JSON" 2>/dev/null; then
    NEEDS_FIX=false
  fi
fi
if [ "$NEEDS_FIX" = true ]; then
  cat > "$KILO_JSON" <<'EOF'
{
  "$schema": "https://app.kilo.ai/config.json",
  "permission": {
    "bash": "allow"
  }
}
EOF
  echo "Wrote/repaired $KILO_JSON."
else
  echo "$KILO_JSON already valid — left as-is."
fi

# ---------- 4c. Model auto-refresh ----------
step "Model auto-refresh (optional)"
echo "scripts/refresh_models.py periodically checks for cheaper/newer models at your"
echo "configured providers and safely upgrades config.yaml (live-tested, old model kept"
echo "as a fallback, every change is its own git commit). See that file's docstring."
PYTHON=$(command -v python3 || command -v python || true)
if [ -n "$PYTHON" ]; then
  "$PYTHON" -m pip install --quiet -r "$ROOT/scripts/requirements.txt"
  read -r -p "Set up a weekly scheduled run now (cron)? (y/N): " setup_schedule
  if [ "$setup_schedule" = "y" ]; then
    bash "$ROOT/scripts/schedule_refresh.sh"
  else
    echo "Skipped. Run it any time yourself: $PYTHON \"$ROOT/scripts/refresh_models.py\" --dry-run"
  fi
else
  echo "Python not found on PATH — skipping. Install Python 3, then optionally run scripts/schedule_refresh.sh later."
fi

# ---------- 4d. Local Ollama (optional) ----------
step "Local LLM via Ollama (optional)"
echo "Running a model on your own GPU/CPU costs \$0 per token, but only helps if your"
echo "hardware can run one at a useful speed. This checks your hardware, recommends a"
echo "model size (or honestly tells you it's not worth it), and asks before doing anything."
if [ -n "$PYTHON" ]; then
  "$PYTHON" "$ROOT/scripts/setup_ollama.py"
else
  echo "Python not found on PATH — skipping. Run scripts/setup_ollama.py later once it's installed."
fi

# ---------- 4e. Model selection preference ----------
step "Model selection preference"
echo "How should the model auto-refresher choose between candidates going forward?"
if [ -n "$PYTHON" ]; then
  "$PYTHON" "$ROOT/scripts/set_preference.py"
fi

# ---------- 4f. Editor integrations ----------
step "Editor/agent integrations (optional)"
echo "5 editors/agents can point at this same LiteLLM + MCP setup -- see editors/README.md."
echo "Kilo Code is already fully configured. For the others:"
if [ -n "$PYTHON" ]; then
  read -r -p "Wire up Cline now (VS Code extension, if installed)? (y/N): " do_cline
  [ "$do_cline" = "y" ] && "$PYTHON" "$ROOT/editors/cline/install.py"
  read -r -p "Wire up Zed now (if installed)? (y/N): " do_zed
  [ "$do_zed" = "y" ] && "$PYTHON" "$ROOT/editors/zed/install.py"
  read -r -p "Wire up GitHub Copilot Chat now (needs an active Copilot subscription)? (y/N): " do_copilot
  [ "$do_copilot" = "y" ] && "$PYTHON" "$ROOT/editors/copilot/install.py"
fi
echo "Aider and OpenHands: see editors/aider/README.md and editors/openhands/README.md."

# ---------- 4g. Dashboard ----------
step "Workflow dashboard (optional)"
echo "One page for everything: container/MCP health, balances, API keys, logs."
if [ -n "$PYTHON" ]; then
  "$PYTHON" -m pip install --quiet -r "$ROOT/dashboard/requirements.txt"
  echo "Start it any time with: $PYTHON \"$ROOT/dashboard/app.py\"  ->  http://127.0.0.1:8877"
fi

# ---------- 5. Manual steps ----------
step "Manual step required: Kilo Code provider wiring"
cat <<EOF
Kilo Code's own provider config isn't reliably settable by dropping a file
in — do this once through its UI:
  1. Install the Kilo Code extension in VS Code if you haven't.
  2. Settings -> Providers -> Custom provider -> Connect
       Base URL : http://127.0.0.1:4000/v1
       API key  : $MASTER_KEY
  3. Settings -> Models -> "Model per Mode" -> set Code/Ask/Debug/Plan/
     Orchestrator to their matching kilo-* model from the new provider.
EOF

step "Optional: host-side companion MCP servers"
cat <<'EOF'
These need their real app running on THIS machine (not in Docker) — set up
only the ones you actually use:

  Blender  - install github.com/ahujasid/blender-mcp's addon, open Blender,
             click "Start MCP Server" in its sidebar (port 9876 — the
             container already reaches it via host.docker.internal).

  Godot    - open your project, then run:
               pip install mcp httpx jsonschema
               python addons/gdai-mcp-plugin-godot/gdai_mcp_server.py --transport http --host 0.0.0.0 --port 9090
             Then add a remote entry in config.yaml pointing at
             http://host.docker.internal:9090/mcp and rebuild.

  Unity    - open your Unity project, install the Unity MCP package, then
             run Window -> MCP for Unity -> Configure All Detected Clients
             to see its real connection details (not fixed in advance).

  Nuclear  - install from nuclearplayer.com, enable Settings -> Integrations
             -> MCP Server, then register the URL it gives you.

  Windows desktop control (CursorTouch/Windows-MCP) - Windows-only, N/A here.
EOF

step "Done"
echo "LiteLLM:      http://127.0.0.1:4000"
echo "Admin UI:     http://127.0.0.1:4000 (log in with the master key below)"
echo "Master key:   $MASTER_KEY"
